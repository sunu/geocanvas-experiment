import { useState } from 'react'
import { CaretDownIcon, CaretRightIcon, PlayIcon, TerminalWindowIcon } from '@phosphor-icons/react'
import type { AnyObject, Runtime } from '@ttx/core'
import { ACCEPTS, followerState, KIND_NAMES, type CodeBoardObject, type FollowerState, type MapBoardObject } from '@ttx/plugins'
import type { BoardObject } from '../board/board'
import { CodeSource, RunError, useRunCell } from './cell'
import { hover, pin, sameElement, useCodeFocus, type CodeElement } from './focus'

/**
 * A footnote under each object that shows a code cell's output (plans/plan-021.md, plan-022): "Generated by code",
 * whether it stands behind its cell (codeOutput.ts, followerState), and, opened, the code to read, edit and run again.
 * The code is the cell's: editing it here edits the cell.
 */

/** What an object shows of which cells: its link, or a map's layers made by code. */
export function sourcesOf(object: AnyObject): { cellId: string; shows: { uploadId?: string; renderedAt?: number }; layer?: { id: string; title: string } }[] {
  if (object.link?.recipe.startsWith('code.')) return [{ cellId: object.link.from, shows: { renderedAt: object.link.args?.renderedAt as number | undefined } }]
  if (object.type !== 'map') return []
  return ((object as MapBoardObject).layers ?? []).flatMap((l) => (l.from ? [{ cellId: l.from, shows: { uploadId: l.input.fileId as string | undefined }, layer: { id: l.id, title: l.title } }] : []))
}

const time = (at: number) => new Date(at).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })

/** What the footnote says about a follower that is behind its cell, or undefined when it is current. */
export function stateText(state: FollowerState, type: string): string | undefined {
  switch (state.state) {
    case 'failed':
      return `The latest run failed. This shows the result from before (${time(state.at)}).`
    case 'otherKind':
      return `The code now gives ${KIND_NAMES[state.kind]}, and a ${type} shows ${(ACCEPTS[type] ?? []).map((k) => KIND_NAMES[k]).join(' or ')}. This shows the earlier result.`
    case 'edited':
      return 'The code changed since this was made. Run it to update.'
    case 'old':
      return 'This shows an earlier result of the code.'
    case 'deleted':
      return 'The code cell was deleted. This keeps its last result.'
    default:
      return undefined
  }
}

type Source = ReturnType<typeof sourcesOf>[number]

/** The short word for a state that is behind, for the summary line and a row's chip. */
const FLAGS: Partial<Record<FollowerState['state'], string>> = { failed: 'run failed', otherKind: 'out of date', old: 'out of date', edited: 'not run', deleted: 'cell deleted' }

/**
 * One quiet line under the object ("Generated by code · Buffer", "2 layers generated by code"), with a flag only
 * when something is behind its cell. Open, a row per element: hovering a row points out the element and its cell
 * (and highlights the layer on a live map); clicking it pins it and opens its details. A feature hovered or
 * clicked on the map (code/focus.ts) opens that layer's row.
 */
export function CodeFootnote({ runtime, object }: { runtime: Runtime; object: BoardObject }) {
  const [listed, setListed] = useState(false)
  const focus = useCodeFocus(object.id)
  const sources = sourcesOf(object)
  if (!sources.length) return null
  const rows = sources.map((source) => {
    const cell = runtime.board.get(source.cellId) as CodeBoardObject | undefined
    const element: CodeElement = { objectId: object.id, cellId: source.cellId, ...(source.layer && { layerId: source.layer.id }) }
    return { source, cell, element, state: followerState(cell, object.type, source.shows) }
  })
  const counts = new Map<string, number>()
  for (const r of rows) {
    const flag = FLAGS[r.state.state]
    if (flag) counts.set(flag, (counts.get(flag) ?? 0) + 1)
  }
  const flags = [...counts].map(([flag, n]) => `${n} ${flag}`)
  const one = rows.length === 1 ? rows[0]! : undefined
  const open = rows.find((r) => sameElement(r.element, focus.open))
  // One element: the line itself opens its details. Several: the line lists them.
  const onLine = () => (one ? pin(sameElement(one.element, focus.open) ? undefined : one.element) : setListed(!listed))
  const expanded = one ? !!open : listed || !!open
  return (
    <div className="ttx-codenote" onPointerDown={(e) => e.stopPropagation()} onDoubleClick={(e) => e.stopPropagation()} onWheel={(e) => e.stopPropagation()}>
      <button
        type="button"
        className={`ttx-codenote__head ${flags.length ? 'is-behind' : ''}`}
        onClick={onLine}
        aria-expanded={expanded}
        onPointerEnter={() => one && hover(one.element)}
        onPointerLeave={() => one && hover(undefined)}
      >
        {expanded ? <CaretDownIcon size={12} aria-hidden /> : <CaretRightIcon size={12} aria-hidden />}
        <TerminalWindowIcon size={12} aria-hidden />
        <span>{one ? `Generated by code${one.cell ? ` · ${one.cell.title}` : ''}` : `${rows.length} ${object.type === 'map' ? 'layers' : 'parts'} generated by code`}</span>
        {flags.map((f) => (
          <span key={f} className="ttx-codenote__flag">
            {one ? f.replace(/^1 /, '') : f}
          </span>
        ))}
      </button>
      {!one && expanded && (
        <div className="ttx-codenote__rows">
          {rows.map((r) => {
            const isOpen = sameElement(r.element, open?.element)
            return (
              <div key={r.source.layer?.id ?? r.source.cellId}>
                <button
                  type="button"
                  className={`ttx-codenote__row ${isOpen ? 'is-open' : ''} ${sameElement(r.element, focus.hovered) ? 'is-hovered' : ''}`}
                  onPointerEnter={() => hover(r.element)}
                  onPointerLeave={() => hover(undefined)}
                  onClick={() => pin(isOpen && focus.pinned ? undefined : r.element)}
                >
                  <span>{r.source.layer?.title ?? object.type}</span>
                  {/* The cell's title, unless the layer is named as the cell (as code.add names it). */}
                  <span className="ttx-codenote__cell">{!r.cell ? 'deleted cell' : r.cell.title !== r.source.layer?.title ? r.cell.title : ''}</span>
                  {FLAGS[r.state.state] && <span className="ttx-codenote__flag">{FLAGS[r.state.state]}</span>}
                </button>
                {isOpen && <Details runtime={runtime} object={object} {...r} />}
              </div>
            )
          })}
        </div>
      )}
      {one && open && <Details runtime={runtime} object={object} {...one} />}
    </div>
  )
}

/** One element's details: why it is behind, the code to read, edit and run, and the ways out. */
function Details({ runtime, object, cell, source, state }: { runtime: Runtime; object: BoardObject; cell: CodeBoardObject | undefined; source: Source; state: FollowerState }) {
  const [editing, setEditing] = useState(false)
  const behind = stateText(state, object.type)
  return (
    <div className="ttx-codenote__body">
      {behind && <p className="ttx-codenote__state">{behind}</p>}
      {cell && <Code runtime={runtime} cell={cell} editing={editing} setEditing={setEditing} />}
      <div className="ttx-codenote__actions">
        {cell && (
          <button type="button" onClick={() => runtime.dispatch('core.view.zoomToSelection', { kind: 'objects', ids: [cell.id] }, {})}>
            Go to cell
          </button>
        )}
        {source.layer ? (
          <button type="button" onClick={() => (pin(undefined), runtime.beginGesture(), runtime.dispatch('map.removeLayer', { kind: 'objects', ids: [object.id] }, { layerId: source.layer!.id }))}>
            Remove layer
          </button>
        ) : (
          <button type="button" onClick={() => (pin(undefined), runtime.beginGesture(), runtime.dispatch('link.remove', { kind: 'objects', ids: [object.id] }, {}))}>
            Unlink
          </button>
        )}
      </div>
    </div>
  )
}

function Code({ runtime, cell, editing, setEditing }: { runtime: Runtime; cell: CodeBoardObject; editing: boolean; setEditing(e: boolean): void }) {
  const { run, running, problem, canRun, why } = useRunCell(runtime, cell.id)
  return (
    <>
      <div className="ttx-codenote__code">
        <CodeSource runtime={runtime} cell={cell} editing={editing} onRun={() => canRun && void run()} onDone={() => setEditing(false)} />
      </div>
      <RunError runtime={runtime} cell={cell} />
      {problem && <p className="ttx-codenote__state">{problem}</p>}
      <div className="ttx-codenote__actions">
        <button
          type="button"
          onClick={() => {
            if (!editing) runtime.beginGesture()
            setEditing(!editing)
          }}
        >
          {editing ? 'Done' : 'Edit'}
        </button>
        <button type="button" disabled={!canRun || running} title={why} onClick={() => void run()}>
          <PlayIcon size={12} aria-hidden /> {running ? 'Running…' : 'Run'}
        </button>
      </div>
    </>
  )
}
