/** Lowercase, no accents, words split by single spaces. Applied to names and to search text alike. */
export const fold = (s: string) =>
  s.toLowerCase().normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, ' ').trim()

const NAMES = new Map(COUNTRIES)

/** Longest name first, so "south sudan" is tried before "sudan". */
const MATCHERS = [...COUNTRIES.map(([iso3, name]) => [fold(name), iso3] as const), ...Object.entries(ALIASES).map(([name, iso3]) => [name, iso3] as const)]
  .sort((a, b) => b[0].length - a[0].length)
  .map(([name, iso3]) => ({ iso3, re: new RegExp(`\\b${name}\\b`, 'g') }))

export const countryName = (iso3: string): string | undefined => NAMES.get(iso3)

/** The countries a folded text names, and the text without them. */
export function extractCountries(folded: string): { countries: string[]; rest: string } {
  const found: { iso3: string; at: number }[] = []
  let rest = folded
  for (const { iso3, re } of MATCHERS) {
    const at = rest.search(re)
    if (at < 0) continue
    if (!found.some((f) => f.iso3 === iso3)) found.push({ iso3, at })
    rest = rest.replace(re, ' ')
  }
  // In the order the text names them. Positions are in the text as it was when each name was found.
  return { countries: found.sort((a, b) => a.at - b.at).map((f) => f.iso3), rest }
}
